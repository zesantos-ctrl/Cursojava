package vetores;

public class Vetor2 {

    private String nome;
    private double preco;

    public Vetor2(String nome, double preco) {
        this.nome = nome;
        this.preco = preco;
    }

    public Vetor2() {
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public double getPreco() {
        return preco;
    }


}
