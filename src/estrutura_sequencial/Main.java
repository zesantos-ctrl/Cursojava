public class Main {
    public static void main(String[] args) {

        /*
        Porcessamento de dados em java
         */

        // Exemplo 1
        int x, y;
        x = 4;

        y = 2 * x;

        System.out.println(x);
        System.out.println(y);

        System.out.println("==================================");

        // Exemplo 2
        int b;

        b = 5;

        double a = 2 * b;
        System.out.println(b);
        System.out.println(a);

        System.out.println("==================================");

        // Exemplo 3

        double q, Q, h, area;

        q = 6.0;
        Q = 8.0;
        h = 5.0;

        area = (q + Q) / 2.0 * h;
        System.out.println(area);

        System.out.println("==================================");

        // Exemplo 4
        int n, m;
        double resultado;

        n = 5;
        m = 2;

        // Casting
        resultado = (double) n / m;
        System.out.println(resultado);


        // Exemplo 5
        double p;
        int t;

        p = 5.0;
        t = (int) a;
        System.out.println(t);

    }
}
